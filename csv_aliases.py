"""Stored column names that are no longer the names the code uses.

A full ledger rebuild replays every snapshot in consolidated/ back to
2025-04, so the code must keep reading headers written by every earlier
version of itself. Those files are the record of what was published on each
day and are never rewritten - the translation happens on read instead.

Keyed by file, not global. `Verified Date` means the date a human recorded a
verdict in dropped_award_status.csv and the date automation last changed one
in auto_verification.csv; a single flat table could not hold both, which is
why `utils.read_rows` resolves the table from the path rather than taking one
map for every file.

Each table maps a stored name to the current one. Two rules make them safe to
apply to a file that has already been migrated, both asserted in
tests/test_csv_aliases.py:

  - no current name may also be a stored name, or a second pass would rename
    it again;
  - no two stored names may map to the same current name, or reading would
    silently merge two columns.
"""

