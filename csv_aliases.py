def is_snapshot(path: str) -> bool:
    """Whether `path` is a daily snapshot rather than the ledger beside it.

    Matches what build_master_ledger.snapshot_files() replays: any CSV in
    consolidated/ except the ledger. Snapshot filenames have changed twice, so
    the directory is the reliable signal, not the name.
    """
    return (
        os.path.basename(os.path.dirname(os.path.abspath(path))) == SNAPSHOT_DIR
        and os.path.basename(path) != LEDGER_BASENAME
    )


def aliases_for(path: str) -> dict[str, str]:
    """The stored-name translation for `path`, empty if it needs none.

    Resolved from the path so that no caller has to know which table applies.
    Forgetting to pass one would not raise - an un-aliased read returns stored
    keys, `row.get()` returns None, and whatever was checking that value stops
    checking it.
    """
    table = _BY_BASENAME.get(os.path.basename(path))
    if table is not None:
        return table
    return SNAPSHOT if is_snapshot(path) else {}


def value_aliases_for(path: str) -> dict[str, dict[str, str]]:
    """Stored cell values for `path` that are no longer the current ones.

    Keyed by the column name *after* header translation, so the two passes
    compose in one order only: rename the columns, then map the cells.
    """
    return SNAPSHOT_VALUES if is_snapshot(path) else {}
